"""Pydantic domain models for EvidenceGuard AI."""
from typing import List, Optional, Literal
from pydantic import BaseModel, Field, ConfigDict, AliasChoices


class EvidenceItem(BaseModel):
    """A trusted factual record in the evidence knowledge base."""
    source_id: str = Field(..., description="Unique identifier for the evidence source, e.g. novatech-001")
    title: str = Field(..., description="Descriptive headline of the evidence record")
    content: str = Field(..., description="Exact factual text content")

    model_config = ConfigDict(frozen=True)


class ClaimVerification(BaseModel):
    """Granular verification result for an individual factual claim."""
    claim: str = Field(
        ...,
        validation_alias=AliasChoices("claim", "text"),
        description="Extracted atomic factual statement from the draft"
    )
    status: Literal["supported", "unsupported", "contradicted"] = Field(
        ...,
        description="Classification of claim against evidence: supported, unsupported, or contradicted"
    )
    evidence_ids: List[str] = Field(
        default_factory=list,
        validation_alias=AliasChoices("evidence_ids", "source_ids"),
        description="Source IDs of evidence used to verify or refute this claim"
    )
    reason: str = Field(..., description="Specific explanation of why the claim is supported or rejected")

    model_config = ConfigDict(populate_by_name=True)


class DraftResult(BaseModel):
    """The initial unverified draft generated by the LLM."""
    answer: str = Field(..., description="Raw answer generated in the first pass")
    model: str = Field(..., description="Model identifier used for drafting")


class CheckResult(BaseModel):
    """The outcome of the skeptical factual claim verification pass."""
    passed: bool = Field(..., description="True if every claim is supported; False if any claim is unsupported or contradicted")
    failure_type: Optional[Literal["evidence_grounding_failure"]] = Field(
        default=None,
        description="The targeted failure family if check failed (evidence_grounding_failure)"
    )
    claims: List[ClaimVerification] = Field(
        default_factory=list,
        description="Claim-by-claim breakdown of the draft"
    )


class FinalResult(BaseModel):
    """The final answer after self-check verification and conditional correction."""
    title: Optional[str] = Field(
        default=None,
        description="Stage 3 title: FINAL VERIFIED RESULT, CORRECTED FINAL RESULT, or FLAGGED FINAL RESULT"
    )
    status: Literal["verified", "corrected", "flagged"] = Field(
        ...,
        description="verified (passed check), corrected (fixed unsupported facts), or flagged (insufficient evidence)"
    )
    answer: str = Field(..., description="The verified, corrected, or safety-flagged answer")
    correction_notes: Optional[str] = Field(
        default=None,
        description="Details on what was corrected or why it was flagged"
    )

    def model_post_init(self, __context) -> None:
        if not self.title:
            titles = {
                "verified": "FINAL VERIFIED RESULT",
                "corrected": "CORRECTED FINAL RESULT",
                "flagged": "FLAGGED FINAL RESULT"
            }
            object.__setattr__(self, "title", titles.get(self.status, "FINAL VERIFIED RESULT"))


class AnswerRequest(BaseModel):
    """Request schema for the /api/v1/answer endpoint."""
    question: str = Field(..., min_length=3, description="User question to be answered against trusted evidence")
    evidence_ids: Optional[List[str]] = Field(
        default=None,
        description="Optional list of specific evidence IDs to ground against. If omitted, all relevant evidence is used."
    )


class AnswerResponse(BaseModel):
    """Comprehensive structured response containing draft, check audit, and final result."""
    question: str = Field(..., description="Original user question")
    provider: str = Field(..., description="Active LLM provider (gemini or mock)")
    model: str = Field(..., description="Active model name (e.g. gemini-2.5-flash or deterministic-mock)")
    evidence_used: List[EvidenceItem] = Field(..., description="The exact evidence records supplied to the pipeline")
    draft: DraftResult = Field(..., description="Initial draft generated in Stage 1")
    check: CheckResult = Field(..., description="Adversarial check results from Stage 2")
    final: FinalResult = Field(..., description="Final result from Stage 3")


class HealthResponse(BaseModel):
    """System health check response."""
    status: str = Field(default="ok")
    provider: str = Field(..., description="Active LLM provider (gemini or mock)")
    model: str = Field(..., description="Configured model name")
    evidence_count: int = Field(..., description="Number of loaded evidence records")
